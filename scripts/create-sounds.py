"""Original, deterministic bell miniatures. Requires ffmpeg with Opus and MP3 encoders."""
import hashlib
import json
import math
from pathlib import Path
import shutil
import struct
import subprocess
import tempfile
import wave

ROOT = Path(__file__).resolve().parent.parent
RATE = 44100
TAU = math.tau


def note(midi):
    return 440 * 2 ** ((midi - 69) / 12)


# D major / pentatonic: a shared, gentle musical vocabulary.
# Each tuple is (start, MIDI note, duration, level, stereo pan, pitch bend).
CUES = {
    'tap': [(0, 81, .17, .7, 0, 0)],
    'shot': [(0, 74, .24, .9, -.12, 4), (.045, 81, .21, .36, .12, 0)],
    'hit': [(0, 78, .28, .85, -.15, 0), (.055, 81, .32, .65, .15, 0)],
    'perfect': [(0, 81, .32, .8, -.22, 0), (.055, 86, .44, .72, .22, 0), (.11, 90, .36, .3, 0, 0)],
    'win': [(0, 74, .4, .7, -.25, 0), (.09, 78, .4, .65, -.08, 0), (.18, 81, .44, .7, .12, 0), (.30, 86, .65, .8, .25, 0)],
    'miss': [(0, 74, .25, .62, -.1, 0), (.12, 69, .35, .55, .1, 0)],
    'collision': [(0, 57, .28, .6, -.12, -1), (.025, 62, .32, .55, .12, 0)],
    'boss': [(0, 62, .55, .55, -.3, 0), (.08, 69, .5, .55, -.15, 0), (.16, 74, .5, .65, 0, 0), (.25, 78, .55, .65, .15, 0), (.36, 81, .7, .8, .3, 0), (.48, 86, .8, .7, 0, 0)],
}


def render(events, path):
    duration = max(start + length for start, _, length, _, _, _ in events) + .26
    count = math.ceil(duration * RATE)
    channels = [[0.0] * count for _ in range(2)]
    for start, midi, length, gain, pan, bend in events:
        frequency = note(midi)
        for i in range(math.ceil(length * RATE)):
            t = i / RATE
            attack = min(1, t / .006)
            release = min(1, max(0, (length - t) / .045))
            envelope = attack * release * math.exp(-4.6 * t / length)
            # A soft FM tine with a quiet octave; no abrupt square-wave edges.
            phase = TAU * frequency * (t + bend * .0012 * (.045 * (1 - math.exp(-t / .045))))
            tine = math.sin(phase + .5 * math.exp(-t * 18) * math.sin(phase * 2))
            value = gain * envelope * (.88 * tine + .12 * math.sin(phase * 2) * math.exp(-t * 14))
            at = round(start * RATE) + i
            for channel, stereo in enumerate([math.sqrt((1 - pan) / 2), math.sqrt((1 + pan) / 2)]):
                channels[channel][at] += value * stereo
                # Two faint, bounded reflections supply a short, airy tail.
                for delay, amount in [(.053, .10), (.109, .045)]:
                    echo = at + round(delay * RATE)
                    if echo < count:
                        channels[1 - channel][echo] += value * stereo * amount
    peak = max(abs(value) for channel in channels for value in channel)
    scale = .42 / max(peak, .01)
    pcm = bytearray()
    for i in range(count):
        for channel in channels:
            pcm.extend(struct.pack('<h', round(channel[i] * scale * 32767)))
    with wave.open(str(path), 'wb') as audio:
        audio.setnchannels(2)
        audio.setsampwidth(2)
        audio.setframerate(RATE)
        audio.writeframes(pcm)
    return duration


def main():
    ffmpeg = shutil.which('ffmpeg')
    if not ffmpeg:
        raise SystemExit('ffmpeg is required to render the audio files')
    output = ROOT / 'public' / 'audio'
    output.mkdir(parents=True, exist_ok=True)
    assets = {}
    report = {}
    with tempfile.TemporaryDirectory(prefix='tangent-bells-') as temp:
        for name, events in CUES.items():
            wav = Path(temp) / f'{name}.wav'
            duration = render(events, wav)
            digest = hashlib.sha256(wav.read_bytes()).hexdigest()[:10]
            assets[name] = {}
            for extension, codec in [('ogg', ['-c:a', 'libopus', '-b:a', '64k', '-vbr', 'on']), ('mp3', ['-c:a', 'libmp3lame', '-q:a', '4'])]:
                filename = f'{name}-{digest}.{extension}'
                subprocess.run([ffmpeg, '-hide_banner', '-loglevel', 'error', '-y', '-i', str(wav), '-map_metadata', '-1', *codec, str(output / filename)], check=True)
                assets[name][extension] = f'audio/{filename}'
            report[name] = {'seconds': round(duration, 3), 'bytes': sum((ROOT / 'public' / value).stat().st_size for value in assets[name].values())}
    (ROOT / 'src' / 'sound-assets.ts').write_text('// Generated by scripts/create-sounds.py; original Tangent Strike miniatures.\nexport const SOUND_ASSETS = ' + json.dumps(assets, indent=2) + ' as const;\n')
    (output / 'README.txt').write_text('TANGENT STRIKE — original melodic sound effects.\nCreated for this game with scripts/create-sounds.py.\nOGG/Opus, with MP3 alternatives. No external samples.\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
